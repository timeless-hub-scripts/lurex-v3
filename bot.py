async def connect_server(project_key: str, guild: discord.Guild, owner_id: int):
    """Send the raw dashboard project key to the live ComVerify API."""
    payload = {
        "project_key": project_key.strip(),
        "guild_id": str(guild.id),
        "guild_name": guild.name,
        "owner_id": str(owner_id),
    }
    timeout = aiohttp.ClientTimeout(total=15)
    async with aiohttp.ClientSession(timeout=timeout) as session:
        async with session.post(
            f"{COMVERIFY_API_URL}/api/login",
            json=payload,
            headers={"Content-Type": "application/json"},
        ) as response:
            try:
                body = await response.json()
            except Exception:
                body = {"success": False, "error": await response.text()}
            return response.status, body


