@bot.tree.command(
    name="login",
    description="Connect this server using a key generated by the ComVerify dashboard.",
)
@app_commands.describe(project_key="The raw project key copied from the ComVerify dashboard.")
async def login(interaction: discord.Interaction, project_key: str):
    if interaction.guild is None:
        await interaction.response.send_message(
            "❌ This command can only be used inside a Discord server.",
            ephemeral=True,
        )
        return
    if not interaction.user.guild_permissions.administrator:
        await interaction.response.send_message(
            "❌ You need Administrator permissions to connect this server.",
            ephemeral=True,
        )
        return
    if not project_key.strip():
        await interaction.response.send_message(
            "❌ Paste the project key generated by the ComVerify dashboard.",
            ephemeral=True,
        )
        return

    await interaction.response.defer(ephemeral=True)
    try:
        status, result = await connect_server(
            project_key, interaction.guild, interaction.user.id
        )
    except Exception as error:
        print(f"Login API error: {error}")
        await interaction.followup.send(
            "❌ I couldn't reach the ComVerify dashboard. "
            "Check COMVERIFY_API_URL and confirm the bot has internet access.",
            ephemeral=True,
        )
        return

    if status == 200 and result.get("success"):
        link_dashboard_server(
            project_id=int(result["project_id"]),
            project_name=result.get("project_name", "ComVerify project"),
            owner_id=str(interaction.user.id),
            guild_id=str(interaction.guild.id),
            guild_name=interaction.guild.name,
            dashboard_server_id=int(result.get("server_id", 0)) or None,
            project_key=project_key.strip(),
        )
        await interaction.followup.send(
            "✅ **Server connected!**\n\n"
            f"This server is now linked to **{result.get('project_name', 'ComVerify project')}**.",
            ephemeral=True,
        )
        return

    if status == 401:
        message = "❌ That project key is invalid, revoked, or expired. Copy a fresh key from the dashboard."
    elif status == 409:
        message = f"❌ {result.get('error', 'This server cannot be linked to that project.')}"
    elif status == 429:
        message = "⏳ Too many login attempts. Please try again later."
    else:
        message = f"❌ Dashboard response `{status}`: {result.get('error', 'Unknown error.')}"
    await interaction.followup.send(message, ephemeral=True)


